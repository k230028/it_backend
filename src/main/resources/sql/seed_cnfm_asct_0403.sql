UPDATE TPRMPP_BCMMTM
   SET CNFM_YN = 'Y',
       LST_CHG_DTM = SYSDATE,
       LST_CHG_USID = 'SYSTEM'
 WHERE ASCT_ID = 'ASCT-2026-0403'
   AND ENO IN ('K230030', 'K230034', 'K230037', 'K230039')
   AND DEL_YN = 'N';

